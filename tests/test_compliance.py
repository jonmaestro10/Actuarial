"""What the control map claims, checked against the system it claims it of.

The ordinary fate of compliance documentation is to describe a system it has
stopped matching, and the reason auditors discount it. The mechanism against
that is here: every row of `docs/compliance/soc2-controls.md` names a pytest
node id, and a control whose test is renamed or deleted fails the build.

Two tests in this file are themselves named by the map, which is deliberate —
the hardening controls have to be evidenced by something, and the something
should be the test that exercises them.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest

from engine.api.hardening import (
    API_CSP, RATE_LIMIT_SCOPE, SECURITY_HEADERS, UI_CSP, RateLimit,
)
from engine.report.compliance import (
    CONTROLS, Control, compliance, read_controls, unresolved_evidence,
)

ROOT = Path(__file__).resolve().parent.parent


@pytest.fixture(scope="module")
def controls():
    return read_controls(ROOT / CONTROLS)


@pytest.fixture(scope="module")
def collected():
    """Every node id pytest collects, asked of pytest itself.

    Collected rather than globbed for `def test_`: a test inside a class, or
    one generated by a fixture, is collected and would not be found by
    reading the source — and a check that under-counts the suite would report
    a live test as missing.
    """
    out = subprocess.run(
        [sys.executable, "-m", "pytest", "--collect-only", "-q", "--no-header",
         "-p", "no:cacheprovider"],
        cwd=ROOT, capture_output=True, text=True, timeout=900,
    )
    assert out.returncode == 0, out.stdout[-3000:] + out.stderr[-2000:]
    ids = [line.strip().split("[", 1)[0]
           for line in out.stdout.splitlines()
           if "::" in line and not line.startswith(("=", "<", "ERROR"))]
    assert ids, "collected no tests at all"
    return ids


# --------------------------------------------------------------------------
# The rule that keeps the map honest
# --------------------------------------------------------------------------

def test_every_control_names_evidence_that_still_exists(controls, collected):
    """**G2's acceptance criterion.** A named test that disappeared fails here.

    This is the whole reason the control map is worth writing down. Without
    it the document drifts from the system silently, and its value to an
    auditor is the value of any unverified assertion.
    """
    missing = unresolved_evidence(controls, collected)
    assert not missing, (
        f"controls cite tests the suite no longer collects: {missing}. Either "
        f"the test was renamed — update the map — or the mechanism is gone, "
        f"in which case the control is no longer satisfied."
    )


def test_every_claimed_control_actually_names_something(controls):
    """Guards a row that satisfies the check above by naming nothing.

    `unresolved_evidence` compares the ids a row *has*. A row with an empty
    evidence cell has none to be missing, so it would pass silently — the
    empty-collection failure, one column over.
    """
    silent = [c.control for c in controls
              if c.claimed and not c.node_ids and not c.generated]
    assert not silent, (
        f"controls {silent} claim to be satisfied and cite no test and no "
        f"generated artifact; they pass the evidence check by having no "
        f"evidence to check"
    )


def test_the_map_records_its_gaps_rather_than_only_its_wins(controls):
    """Guards a control map whose totals are a function of what was written.

    A map with no unsatisfied rows is a map nobody audited. The first
    question a good auditor asks is what is missing, and a document that
    cannot answer it has answered it.
    """
    unclaimed = [c for c in controls if not c.claimed]
    assert unclaimed, (
        "no control is marked 'not claimed'. Either every Trust Services "
        "criterion this system touches is genuinely satisfied — which would "
        "be remarkable — or the gaps stopped being written down."
    )


def test_a_control_map_that_parses_to_nothing_is_an_error(tmp_path):
    """Guards the shape this repo keeps being bitten by.

    An empty parse reports zero unresolved references, which is byte-identical
    to a clean bill of health. A renamed heading or a reformatted table would
    produce it.
    """
    empty = tmp_path / "soc2-controls.md"
    empty.write_text("# SOC 2 control map\n\nNo tables here.\n")
    with pytest.raises(ValueError, match="zero controls"):
        read_controls(empty)

    with pytest.raises(FileNotFoundError):
        read_controls(tmp_path / "absent.md")


def test_the_generated_section_says_when_it_did_not_check(controls):
    """Guards an unchecked binder reading like a checked one.

    Built without a test inventory, the section cannot verify a single
    reference. Reporting that identically to a verified build is the same
    defect as a skipped measurement reading as a passing one.
    """
    unchecked = compliance([], ROOT / CONTROLS)
    assert unchecked["evidence_checked"] is False
    assert unchecked["unresolved_evidence"] == {}, (
        "with nothing collected, every reference is trivially 'missing' or "
        "trivially 'fine'; the flag is what distinguishes them"
    )


def test_the_section_stays_available_even_with_unsatisfied_controls():
    """§1.5's rule, at the section level.

    `available=False` means "this pack could not look", not "this pack looked
    and found gaps". Collapsing the two would let a build that failed to read
    the map look like a system with nothing to report.
    """
    content = compliance([], ROOT / CONTROLS)
    assert content["available"] is True
    assert content["n_not_claimed"] > 0


