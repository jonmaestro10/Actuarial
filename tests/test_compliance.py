def test_the_map_carries_the_leak_it_would_rather_not_mention(controls):
    """Guards the inconvenient sentence being quietly dropped.

    A security posture is worth what its most inconvenient sentence is worth.
    Cross-tenant compute deduplication leaves a liveness oracle, and a control
    map that omits it is describing a different system.
    """
    text = (ROOT / CONTROLS).read_text(encoding="utf-8").lower()
    assert "liveness oracle" in text
    assert "dedupe_across_tenants" in text

    content = compliance([], ROOT / CONTROLS)
    assert content["shared_compute_leak"], (
        "the generated section carries no leak statement, so the binder an "
        "auditor receives omits what the document says"
    )
