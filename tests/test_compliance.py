def test_every_response_carries_the_headers_that_matter_for_json():
    """**Named by CC6.6.**

    `nosniff` is the one that matters most: without it a browser may sniff a
    JSON response as HTML and execute it, which is the path from "returns
    user data" to "runs script in the API's origin". `no-referrer` because
    run ids are request fingerprints and a referrer leaks them onward;
    `no-store` because results are a tenant's numbers and a shared cache
    holding them is a cross-tenant read no route check can see.
    """
    pytest.importorskip("fastapi")
    from fastapi.testclient import TestClient

    from engine.api import create_app

    with TestClient(create_app(max_workers=1)) as client:
        response = client.get("/models")
        for header, value in SECURITY_HEADERS.items():
            assert response.headers.get(header) == value, header
        assert response.headers.get("Content-Security-Policy") == API_CSP
        assert response.headers.get("Cache-Control") == "no-store"

        # The UI needs its own two assets, so it gets a different policy —
        # and must not be handed `default-src 'none'`, which would render a
        # blank page while every header looked correct.
        page = client.get("/ui")
        assert page.headers.get("Content-Security-Policy") == UI_CSP
        assert "'self'" in UI_CSP and "'self'" not in API_CSP


def test_hsts_is_not_emitted_by_the_application():
    """Guards a header that promises something this process cannot know.

    Strict-Transport-Security is a promise about a *scheme*. This process
    does not know whether it sits behind TLS: emitted from a plain-HTTP
    deployment it does nothing, and where TLS does terminate the header
    belongs on the proxy holding the certificate. A header that is present
    and meaningless is worse than absent, because it is read as coverage.
    """
    assert not any(h.lower() == "strict-transport-security"
                   for h in SECURITY_HEADERS)


def test_the_rate_limit_states_what_it_is_not():
    """**Named by A1.1.**

    A control believed to do more than it does is worse than no control,
    because it stops anyone looking. This limiter is per-process, so N
    replicas admit N times the rate, and it is not a DoS control because an
    unauthenticated caller never reaches it. Both sentences have to survive.
    """
    for required in ("NOT a distributed limit", "NOT a denial-of-service",
                     "own buckets"):
        assert required in RATE_LIMIT_SCOPE, (
            f"the rate limit's scope stopped saying {required!r}"
        )


def test_the_rate_limit_admits_the_rate_and_then_refuses():
    """The mechanism behind the claim, so A1.1 is not evidenced by prose alone."""
    limit = RateLimit(rate=3, window=60.0)
    assert [limit.check("k", now=0.0) for _ in range(3)] == [True] * 3
    assert limit.check("k", now=0.0) is False
    # A different key is a different bucket, or one noisy client would take
    # everyone else's quota with it.
    assert limit.check("other", now=0.0) is True
    # And the window slides rather than resetting: a fixed window admits
    # twice the rate across its boundary.
    assert limit.check("k", now=60.1) is True


def test_retry_after_is_never_zero():
    """Guards a rate limit that becomes a busy loop.

    `Retry-After: 0` invites an immediate retry which also fails. A
    well-behaved client and a correct server then spin against each other.
    """
    limit = RateLimit(rate=1, window=60.0)
    limit.check("k", now=0.0)
    assert limit.retry_after("k", now=59.99) >= 1
    assert limit.retry_after("never-seen", now=0.0) >= 1


def test_a_rate_limited_response_still_carries_the_security_headers():
    """Guards the error path losing the headers the success path has.

    A 429 is generated before the middleware's normal response path, which is
    exactly the kind of early return that ships without them.
    """
    pytest.importorskip("fastapi")
    from fastapi.testclient import TestClient

    from engine.api import create_app

    with TestClient(create_app(max_workers=1, rate_limit=2)) as client:
        for _ in range(2):
            client.get("/models")
        blocked = client.get("/models")
        assert blocked.status_code == 429
        assert blocked.headers.get("Retry-After")
        for header, value in SECURITY_HEADERS.items():
            assert blocked.headers.get(header) == value, header


def test_health_is_never_rate_limited():
    """Guards a liveness probe that a busy client can turn into an outage.

    `/health` is the one route with no role requirement because a load
    balancer has no token. For the same reason it must not be the route that
    starts failing when some other client is noisy — the orchestrator would
    read 429 as unhealthy and restart a pod that is fine.
    """
    pytest.importorskip("fastapi")
    from fastapi.testclient import TestClient

    from engine.api import create_app

    with TestClient(create_app(max_workers=1, rate_limit=1)) as client:
        client.get("/models")
        assert client.get("/models").status_code == 429
        for _ in range(5):
            assert client.get("/health").status_code == 200


def test_the_limiter_is_off_unless_a_deployment_asks_for_it():
    """The library and the local demo must behave as they did.

    Same posture as authentication and tenancy: a capacity decision belongs
    to a deployment, and a library that silently rate-limits its caller is a
    library with an opinion about a program it cannot see.
    """
    pytest.importorskip("fastapi")
    from fastapi.testclient import TestClient

    from engine.api import create_app

    with TestClient(create_app(max_workers=1)) as client:
        for _ in range(50):
            assert client.get("/health").status_code == 200


